/// מחזיר את קטגוריית אוצריא ("/תנ"ך") עבור מחרוזת תגיות מהקטלוג,
/// או null כשאין התאמה — ואז הספר יוצג תחת "עוד מהיברובוקס".
export function mapHebrewBooksCategory(categories: string | null): string | null {
  if (!categories) return null;
  const tags = new Set(
    categories
      .split('|')
      .map((tag) => tag.trim())
      .filter((tag) => tag !== ''),
  );
  if (tags.size === 0) return null;
  for (const rule of rules) {
    if (rule.tags.some((tag) => tags.has(tag))) return rule.category;
  }
  return null;
}
